"""Animation data for the calc-animation-from-spr case, from the user's disc (AI-assisted), ISC.

calc-animation-from-spr and its decompressors read compressed joint animations,
and a hand-made stream would only test noise. So when the user's own GAME.CGO
is available, this copies the first two frames of five of Jak's animations out of
the eichar art group into build/mips2c/anim_case.h: two that between them use
every per-joint codec value in Jak's control bits, and one of each matrix-bits
setting (0, 1 and 3). It goes to build/mips2c/anim_case.h, which mips2c_cases.h includes if it exists.
build/ is not committed, so no disc data enters the repository; without the disc
the case is simply left out.

GAME.CGO is looked for in $DC_JAK_CGO_DIR, then iso_data/jak1/CGO (where the
OpenGOAL extractor's users keep the disc's files).

  python anim_case_data.py [--cgo PATH]   # writes or removes the header
"""
import argparse
import os
from pathlib import Path
import struct
import sys

PORT = Path(__file__).resolve().parent
sys.path.insert(0, str(PORT))
import level_contents  # noqa: E402

HEADER = PORT / 'build/mips2c/anim_case.h'
ANIMS = ('eichar-flop-down-loop', 'eichar-jump-short-land', 'eichar-yellow-running-blast-end',
         'eichar-attack-from-jump', 'eichar-duck-roll-end')
FRAMES = 2  # enough for a pair upload (frame-qwc doubled)


def find_cgo():
    for base in (os.environ.get('DC_JAK_CGO_DIR'), PORT.parents[1] / 'iso_data/jak1/CGO'):
        if base:
            for name in ('GAME.CGO', 'game.cgo'):
                if (Path(base) / name).is_file():
                    return Path(base) / name
    return None


def animations(cgo):
    """name -> (num_frames, fixed_qwc, frame_qwc, fixed bytes, frame bytes) for ANIMS."""
    obj = level_contents.object_bytes(cgo, 'eichar')
    code_size, found = level_contents.basics(obj)
    data = obj[16:16 + code_size]  # unlinked: pointer words hold offsets into this
    out = {}
    for at, type_name in found:
        if type_name != 'art-joint-anim':
            continue
        basic = at + 4
        name_at, = struct.unpack_from('<I', data, basic + 4)
        length, = struct.unpack_from('<I', data, name_at)
        name = data[name_at + 4:name_at + 4 + length].decode('ascii')
        if name not in ANIMS:
            continue
        control, = struct.unpack_from('<I', data, basic + 40)
        frames, fixed_qwc, frame_qwc, fixed = struct.unpack_from('<4I', data, control)
        frames = min(frames, FRAMES)
        frame_at = struct.unpack_from(f'<{frames}I', data, control + 16)
        # Frames laid end to end, as a pair upload (frame-qwc doubled) reads them.
        frame_bytes = b''.join(data[f:f + 16 * frame_qwc] for f in frame_at)
        out[name] = (frames, fixed_qwc, frame_qwc, data[fixed:fixed + 16 * fixed_qwc], frame_bytes)
    missing = [a for a in ANIMS if a not in out]
    if missing:
        raise ValueError(f'{cgo}: eichar has no {", ".join(missing)}')
    return out


def c_bytes(blob):
    rows = [', '.join(f'0x{b:02x}' for b in blob[i:i + 16]) for i in range(0, len(blob), 16)]
    return '{\n  ' + ',\n  '.join(rows) + '}'


def write_header(cgo, path=HEADER):
    anims = animations(cgo)
    lines = ['/* Generated by anim_case_data.py from the user\'s GAME.CGO; not committed. */',
             '#define DC_M2C_ANIM_COUNT %du' % len(ANIMS)]
    for i, name in enumerate(ANIMS):
        frames, fixed_qwc, frame_qwc, fixed, frame_bytes = anims[name]
        lines.append(f'static const unsigned char dc_m2c_anim{i}_fixed[{len(fixed)}] = {c_bytes(fixed)};')
        lines.append(f'static const unsigned char dc_m2c_anim{i}_frames[{len(frame_bytes)}] = {c_bytes(frame_bytes)};')
    lines.append('static const struct { const char *name; uint32_t frames, fixed_qwc, frame_qwc;')
    lines.append('  const unsigned char *fixed, *frame; } dc_m2c_anims[DC_M2C_ANIM_COUNT] = {')
    for i, name in enumerate(ANIMS):
        frames, fixed_qwc, frame_qwc, _, _ = anims[name]
        lines.append(f'  {{"{name}", {frames}u, {fixed_qwc}u, {frame_qwc}u, dc_m2c_anim{i}_fixed, dc_m2c_anim{i}_frames}},')
    lines.append('};')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines) + '\n')
    return anims


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--cgo', type=Path)
    args = parser.parse_args()
    cgo = args.cgo or find_cgo()
    if not cgo:
        HEADER.unlink(missing_ok=True)
        print('no GAME.CGO found: the animation case is left out')
        return
    for name, (frames, fixed_qwc, frame_qwc, _, _) in write_header(cgo).items():
        print(f'{name}: {frames} frames, fixed {fixed_qwc} qw, frame {frame_qwc} qw')


if __name__ == '__main__':
    main()
