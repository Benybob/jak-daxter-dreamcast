"""Shared hand-written SH-4 helpers that lowered GOAL code calls (AI-assisted).

Long templates are written once here instead of inline at every use: each
call is MOV.L @(disp,PC),Rn; JSR @Rn; NOP plus one literal per function.
The runtime installs them beside its C bridges (goal_bridge.c), so they
exist wherever lowered code can run. Register contracts:

  dc-sh4-float-to-int  FR0 -> R0:R1 (R1 the sign). Clobbers FR1, FPUL, R2, T.
  dc-sh4-shl/shr/sar   R0:R1 by R2 (six bits) -> R0:R1. Clobbers R2-R4, T.
  dc-sh4-idiv/udiv/imod/umod  R0 by R2 -> R0:R1. Clobbers R3-R7, T; faults
                       call dc-c-integer-error and return zero.

Run as a script to regenerate sh4_helpers.h.
"""
import argparse
from pathlib import Path

from division_sh4 import emit_div32
from sh4_backend import Emitter
from shift_sh4 import emit_shift64


def float_to_int():
    # The pinned frontend's cvttss2si contract: NaN and out-of-range give 0x80000000.
    e=Emitter()
    e.constant(0,0x4f000000); e.word(0x405a); e.word(0xf10d)  # +2^31 -> FR1
    e.rr(0xf005,1,0); e.branch('bf','invalid')  # 2^31 > input; excludes NaN and +overflow
    e.word(0xf03d); e.word(0x005a)  # FTRC FR0,FPUL; STS FPUL,R0
    e.branch('bra','done'); e.label('invalid'); e.constant(0,0x80000000)
    e.label('done'); e.mov(1,0); e.immediate(2,-31); e.rr(0x400c,1,2)  # SHAD: R1 = sign
    e.ret()
    return e


def shift(kind):
    e=Emitter(); emit_shift64(e,kind,None,'shift'); e.ret()
    return e


def division(signed,remainder):
    # PR is saved: the fault path calls the integer error bridge.
    e=Emitter(); e.word(0x4f22)  # STS.L PR,@-R15
    emit_div32(e,signed,remainder,'div')
    e.word(0x4f26); e.ret()  # LDS.L @R15+,PR
    return e


CORE={'dc-sh4-float-to-int':float_to_int,
      'dc-sh4-shl':lambda: shift('left'),
      'dc-sh4-shr':lambda: shift('logical'),
      'dc-sh4-sar':lambda: shift('arithmetic')}
INTEGER={'dc-sh4-idiv':lambda: division(True,False),
         'dc-sh4-udiv':lambda: division(False,False),
         'dc-sh4-imod':lambda: division(True,True),
         'dc-sh4-umod':lambda: division(False,True)}


def header():
    lines=['/* Generated by sh4_helpers.py (AI-assisted): shared SH-4 helpers for lowered GOAL code. */',
           '#ifndef DC_SH4_HELPERS_H','#define DC_SH4_HELPERS_H','#include "goal_module.h"']
    for group,helpers in (('core',CORE),('integer',INTEGER)):
        exports=[]
        for name,build in helpers.items():
            data,relocations=build().finish()
            ident='dc_sh4_'+name[7:].replace('-','_')
            lines.append(f'static const unsigned char {ident}_code[{len(data)}] = {{'+','.join(str(b) for b in data)+'};')
            if relocations:
                lines.append(f'static const dc_goal_code_relocation {ident}_relocations[] = {{'+
                             ','.join(f'{{{r["offset"]}u,"{r["symbol"]}"}}' for r in relocations)+'};')
            exports.append(f'{{"{name}",{ident}_code,{len(data)}u,'+
                           (f'{ident}_relocations,{len(relocations)}u}}' if relocations else 'NULL,0u}'))
        lines.append(f'#define DC_SH4_{group.upper()}_HELPER_COUNT {len(exports)}u')
        lines.append(f'#define DC_SH4_{group.upper()}_HELPERS '+','.join(exports))
    lines.append('#endif')
    return '\n'.join(lines)+'\n'


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--output',type=Path,default=Path(__file__).with_name('sh4_helpers.h'))
    parser.parse_args().output.write_text(header(),newline='\n')
