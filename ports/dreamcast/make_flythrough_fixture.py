"""Stage a camera path through a level: terrain strip, instances, expectations (AI-assisted), ISC.

    python make_flythrough_fixture.py BACKGROUND.glb PACKAGE.dci2 OUT_DIR
           [--frames 30] [--length 60] [--half 14] [--reference REF.dci]

The terrain keeps the GLB's tfrag roots (default normal, lowres, trans and dirt:
the last two are BLEND, drawn in the translucent list). The camera starts as
make_instance_fixture's (aimed at the package's densest
cell) and its target moves LENGTH meters along the camera's own horizontal view
direction over FRAMES frames. The terrain is the background GLB's opaque tfrag
cropped to every 16 m cell a HALF-meter window along the path can touch, with
material probes for the package (tfrag_glb.py), built into stored-block sectors
(prepare_render_sectors.py at zlib level 0, for sector_inflate_stored.c) in
OUT_DIR with the package beside them; nothing in OUT_DIR is committed.

Writes build/flythrough_fixture.h for flythrough_main.c: per frame the target,
the window query, the window's face count and CRC (assemble_window, which the
native retarget must reproduce), and the instances, triangles and LODs the
instance pass must visit (single precision, as make_instance_fixture does);
plus the GLB-to-catalog material map. --reference writes the DCI1 that
dci1_reference.py draws for the last frame.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import shutil
import zlib

import make_instance_fixture as mf
import make_village_fixture as mv
import prepare_render_sectors as rs
import tfrag_glb
import tie_lods


def path(target, frames, length):
    """Targets along the camera's horizontal view direction (yaw: forward is
    (-sin yaw, cos yaw) in XZ for render_world_view.c's matrix)."""
    fx, fz = -math.sin(mf.YAW), math.cos(mf.YAW)
    out = []
    for i in range(frames):
        s = length * i / max(1, frames - 1)
        out.append([mf.f32(target[0] + fx * s), target[1], mf.f32(target[2] + fz * s)])
    return out


def make(glb, package, out, frames=30, length=60.0, half=14.0, header='build/flythrough_fixture.h',
         roots=('normal', 'lowres', 'trans', 'dirt')):
    out = Path(out)
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    blob = Path(package).read_bytes()
    start = mf.camera(*mf.read(blob))
    targets = path(start, frames, length)
    margin = half + 2 * 16.0
    rect = (min(t[0] for t in targets) - margin, max(t[0] for t in targets) + margin,
            min(t[2] for t in targets) - margin, max(t[2] for t in targets) + margin)
    background = Path(glb).read_bytes()
    cut, _ = tfrag_glb.cut(background, roots, rect=rect, probe_package=blob)
    doc, binary = rs.parse_glb_bytes(cut)
    rs.ZLIB_LEVEL = 0
    packet = rs.build_package(doc, binary, source_sha256=hashlib.sha256(cut).digest())
    rs.publish_package(out / 'sectors-staging', packet)
    for item in (out / 'sectors-staging').iterdir():
        shutil.move(str(item), str(out / item.name))
    (out / 'sectors-staging').rmdir()
    (out / 'package.dci').write_bytes(blob)
    head = rs.parse_manifest(packet.manifest)
    sha = head['source_sha256'].hex()
    blend = {i for i, m in enumerate(head['materials']) if m['base_flags'] & rs.FLAG_BLEND}
    rows = []
    for t in targets:
        query = (t[0] - half, t[0] + half, t[2] - half, t[2] + half)
        faces = rs.assemble_window(packet, query)
        raw = b''.join(f['raw'] for f in faces)
        view = tie_lods.flatten(blob, t[0], t[2])
        _, tris = mf.expected(*mf.read(view), t, mf.DRAW_DISTANCE)
        lods = mf.lod_counts(blob, t, mf.DRAW_DISTANCE)
        rows.append({'target': t, 'query': query, 'faces': len(faces), 'crc': rs.crc32(raw),
                     'blend_faces': sum(1 for x in faces if x['material_id'] in blend),
                     'instances': sum(lods), 'triangles': tris, 'lods': lods})
    glb_doc = json.loads(tfrag_glb.read_chunks(background)[0][1])
    mapping = mv.material_map(out, tfrag_glb.probe_materials(blob, glb_doc))
    f = lambda v: repr(mf.f32(v)) + 'f'  # noqa: E731
    text = ['/* Generated by make_flythrough_fixture.py (AI-assisted); not committed. */',
            f'#define FLY_FRAMES {frames}u', f'#define FLY_PACKAGE_BYTES {len(blob)}u',
            f'#define FLY_PACKAGE_CRC {zlib.crc32(blob)}u',
            f'static const char fly_source_sha[]="{sha}";',
            f'static const float fly_yaw={f(mf.YAW)},fly_pitch={f(mf.PITCH)},fly_distance={f(mf.DISTANCE)},'
            f'fly_draw_distance={f(mf.DRAW_DISTANCE)};',
            'typedef struct {float target[3];dc_render_query query;uint32_t faces,crc,instances,triangles,lods[4];} fly_frame;',
            'static const fly_frame fly_frames[FLY_FRAMES]={']
    for r in rows:
        q = r['query']
        text.append('{{%s},{%s},%du,%du,%du,%du,{%s}},' % (
            ','.join(f(v) for v in r['target']), ','.join(f(v) for v in (q[0], q[2], q[1], q[3])),
            r['faces'], r['crc'], r['instances'], r['triangles'], ','.join(f'{n}u' for n in r['lods'])))
    text.append('};')
    slots = max(mapping) + 1 if mapping else 1
    text.append(f'#define FLY_MATERIAL_SLOTS {slots}u')
    text.append('static const uint16_t fly_material_map[FLY_MATERIAL_SLOTS]={'
                + ','.join(f'{mapping.get(i, 0xffff)}u' for i in range(slots)) + '};')
    Path(header).parent.mkdir(parents=True, exist_ok=True)
    Path(header).write_text('\n'.join(text) + '\n', newline='\n')
    report = {'ai_assisted': True, 'frames': frames, 'length_m': length, 'crop': list(rect),
              'terrain_sources': rs.parse_manifest(packet.manifest)['source_count'],
              'max_window_faces': max(r['faces'] for r in rows), 'textured_materials': len(mapping),
              'blend_faces_by_frame': [r['blend_faces'] for r in rows],
              'max_instance_triangles': max(r['triangles'] for r in rows), 'start': start, 'end': targets[-1]}
    (out / 'FLY.json').write_text(json.dumps(report, indent=1), newline='\n')
    return report, rows


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('glb', type=Path)
    ap.add_argument('package', type=Path)
    ap.add_argument('out', type=Path)
    ap.add_argument('--frames', type=int, default=30)
    ap.add_argument('--length', type=float, default=60.0)
    ap.add_argument('--half', type=float, default=14.0)
    ap.add_argument('--reference', type=Path, help='the DCI1 dci1_reference.py draws for the last frame')
    a = ap.parse_args()
    report, rows = make(a.glb, a.package, a.out, a.frames, a.length, a.half)
    if a.reference:
        blob, _ = mv.reference(a.out, a.package, a.half, rows[-1]['target'])
        a.reference.write_bytes(blob)
    print(json.dumps(report, indent=1))


if __name__ == '__main__':
    main()
