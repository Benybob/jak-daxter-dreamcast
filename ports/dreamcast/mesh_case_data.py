"""Collision meshes for the collide-cache case, from the user's disc (AI-assisted), ISC.

The collide-cache fill case packs a small grid by hand. When the user's own
village1 DGO is available, this copies the three largest collide-frag-meshes of
its BSP (packed vertices, strips and pat indices, with the level's pat array)
into build/mips2c/mesh_case.h, which mips2c_cases.h includes if it exists. build/
is not committed, so no disc data enters the repository; without the disc the
case is left out.

VI1.DGO is looked for in $DC_JAK_DGO_DIR, then iso_data/jak1/DGO.

  python mesh_case_data.py [--dgo PATH]   # writes or removes the header
"""
import argparse
import os
from pathlib import Path
import struct
import sys

PORT = Path(__file__).resolve().parent
sys.path.insert(0, str(PORT))
import level_contents  # noqa: E402

HEADER = PORT / 'build/mips2c/mesh_case.h'
MESHES = 3


def find_dgo():
    for base in (os.environ.get('DC_JAK_DGO_DIR'), PORT.parents[1] / 'iso_data/jak1/DGO'):
        if base:
            for name in ('VI1.DGO', 'vi1.dgo'):
                if (Path(base) / name).is_file():
                    return Path(base) / name
    return None


def meshes(dgo):
    """The MESHES largest collide-frag-meshes (by poly count, then vertices), and
    the pat array they index."""
    obj = level_contents.object_bytes(dgo, 'village1-vis')
    code_size, found = level_contents.basics(obj)
    data = obj[16:16 + code_size]  # unlinked: pointer words hold offsets into this
    rows = []
    for at, type_name in found:
        if type_name != 'collide-frag-mesh':
            continue
        basic = at + 4
        packed, pats = struct.unpack_from('<2I', data, basic)
        strip_len, polys = struct.unpack_from('<2H', data, basic + 8)
        base = struct.unpack_from('<3i', data, basic + 12)
        verts, vertex_qwc, total_qwc = data[basic + 24], data[basic + 25], data[basic + 26]
        rows.append((polys, verts, packed, pats, strip_len, base, vertex_qwc, total_qwc))
    rows.sort(key=lambda r: (r[0], r[1]), reverse=True)
    chosen = rows[:MESHES]
    if len({r[3] for r in chosen}) != 1:
        raise ValueError('the chosen meshes do not share a pat array')
    out, used = [], 0
    for polys, verts, packed, _, strip_len, base, vertex_qwc, total_qwc in chosen:
        blob = data[packed:packed + 16 * total_qwc]
        index_at = 16 * vertex_qwc + strip_len
        used = max(used, max(blob[index_at:index_at + polys]) + 1)
        out.append({'polys': polys, 'verts': verts, 'strip_len': strip_len, 'base': base,
                    'vertex_qwc': vertex_qwc, 'total_qwc': total_qwc, 'packed': blob})
    pats = data[chosen[0][3]:chosen[0][3] + 4 * used]
    return out, pats


def c_bytes(blob):
    rows = [', '.join(f'0x{b:02x}' for b in blob[i:i + 16]) for i in range(0, len(blob), 16)]
    return '{\n  ' + ',\n  '.join(rows) + '}'


def write_header(dgo, path=HEADER):
    found, pats = meshes(dgo)
    lines = ['/* Generated by mesh_case_data.py from the user\'s VI1.DGO; not committed. */',
             '/* disc cases: 1 */',
             f'#define DC_M2C_MESH_COUNT {len(found)}u',
             f'static const unsigned char dc_m2c_mesh_pats[{len(pats)}] = {c_bytes(pats)};']
    for i, m in enumerate(found):
        lines.append(f'static const unsigned char dc_m2c_mesh{i}_packed[{len(m["packed"])}] = {c_bytes(m["packed"])};')
    lines.append('static const struct { uint16_t polys, strip_len; uint8_t verts, vertex_qwc, total_qwc;')
    lines.append('  int32_t base[3]; const unsigned char *packed; } dc_m2c_meshes[DC_M2C_MESH_COUNT] = {')
    for i, m in enumerate(found):
        b = m['base']
        lines.append(f'  {{{m["polys"]}, {m["strip_len"]}, {m["verts"]}, {m["vertex_qwc"]}, {m["total_qwc"]}, '
                     f'{{{b[0]}, {b[1]}, {b[2]}}}, dc_m2c_mesh{i}_packed}},')
    lines.append('};')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines) + '\n')
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--dgo', type=Path)
    args = parser.parse_args()
    dgo = args.dgo or find_dgo()
    if not dgo:
        HEADER.unlink(missing_ok=True)
        print('no VI1.DGO found: the collision mesh case is left out')
        return
    for m in write_header(dgo):
        print(f'{m["polys"]} polys, {m["verts"]} vertices, base {m["base"]}')


if __name__ == '__main__':
    main()
