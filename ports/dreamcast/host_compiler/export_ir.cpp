static const char* reg_class(RegClass value) {
  switch(value) {
    case RegClass::GPR_64: return "gpr64";
    case RegClass::FLOAT: return "float";
    case RegClass::INT_128: return "int128";
    case RegClass::VECTOR_FLOAT: return "vector_float";
    default: return "invalid";
  }
}

using StaticNames=std::unordered_map<const StaticObject*,std::string>;
static std::string native_value_type(const TypeSpec& spec,const TypeSystem& types) {
  if(spec.base_type()=="none" || spec.base_type()=="function") return spec.print();
  const auto* type=types.lookup_type_allow_partial_def(spec);
  // Preserve GOAL enum names separately; their declared underlying scalar
  // layout determines the native ABI. Never treat 128-bit/vector enums as GPRs.
  if(const auto* enumeration=dynamic_cast<const EnumType*>(type)) {
    const int bytes=enumeration->get_load_size();
    if(!enumeration->is_boxed() && enumeration->get_offset()==0 &&
       enumeration->get_preferred_reg_class()==RegClass::GPR_64 &&
       (bytes==1 || bytes==2 || bytes==4 || bytes==8))
      return enumeration->get_load_signed()?"int":"uint";
  }
  // User-defined reference types are 32-bit addresses in scalar containers.
  // Non-reference aggregates and their 128-bit values stay unsupported.
  if(type->is_reference() && type->get_load_size()==4) return "object";
  return spec.print();
}
// FunctionEnv::params also contains (local-vars), so only the original
// constrained entry values and their generated prefix copies define the ABI.
// Fixed process/self entries remain explicit until their ABI is implemented.
static void export_parameters(FunctionEnv& function,const TypeSystem& types,json& fn) {
  fn["locals"]=json::array();
  fn["implicit_parameters"]=json::array();
  std::vector<int> incoming;
  std::unordered_set<int> named_arguments,implicit;
  if(!function.code().empty() && dynamic_cast<IR_ValueReset*>(function.code().front().get())) {
    for(const auto& reg:function.code().front()->to_rai().write) {
      bool argument=false,fixed=false;
      for(const auto& constraint:function.constraints()) {
        if(constraint.ireg.id!=reg.id) continue;
        if(constraint.contrain_everywhere) fixed=true;
        else if(constraint.instr_idx==0) argument=true;
      }
      if(argument==fixed) throw std::runtime_error("ambiguous or unconstrained entry value in "+function.name());
      if(fixed) implicit.insert(reg.id);
      else incoming.push_back(reg.id);
    }
  }
  for(size_t index=0;index<incoming.size();++index) {
    if(index+1>=function.code().size() || !dynamic_cast<IR_RegSet*>(function.code()[index+1].get()))
      throw std::runtime_error("missing generated argument copy in "+function.name());
    const auto copy=function.code()[index+1]->to_rai();
    if(copy.read.size()!=1 || copy.write.size()!=1 || copy.read[0].id!=incoming[index])
      throw std::runtime_error("invalid generated argument copy in "+function.name());
    const int local=copy.write[0].id;
    size_t matches=0;
    for(const auto& [name,value]:function.params) {
      if(value->ireg().id!=local) continue;
      ++matches;
      fn["parameters"].push_back({{"name",name.name_ptr},{"register",incoming[index]},
          {"local_register",local},{"type",value->type().print()},
          {"abi_type",native_value_type(value->type(),types)}});
    }
    // Upstream autogenerated inspect methods have constrained arguments but
    // no source-name map. Derive their types from the exact copied RegVal;
    // the generated name is only a label, never an invented incoming value.
    if(matches==0 && function.params.empty()) {
      for(const auto& value:function.reg_vals()) {
        if(value->ireg().id!=local) continue;
        ++matches;
        fn["parameters"].push_back({{"name","arg-"+std::to_string(index)},
            {"name_source","frontend-generated"},{"register",incoming[index]},
            {"local_register",local},{"type",value->type().print()},
            {"abi_type",native_value_type(value->type(),types)}});
      }
    }
    if(matches!=1 || !named_arguments.insert(local).second)
      throw std::runtime_error("ambiguous generated argument name in "+function.name());
  }
  std::vector<std::pair<int,json>> locals,fixed;
  for(const auto& [name,value]:function.params) {
    const int reg=value->ireg().id;
    if(named_arguments.count(reg)) continue;
    json entry={{"name",name.name_ptr},{"register",reg},{"type",value->type().print()},
                {"abi_type",native_value_type(value->type(),types)}};
    if(implicit.count(reg)) { entry["kind"]="fixed_entry"; fixed.emplace_back(reg,std::move(entry)); }
    else locals.emplace_back(reg,std::move(entry));
  }
  if(fixed.size()!=implicit.size()) throw std::runtime_error("unnamed fixed entry in "+function.name());
  const auto order=[](const auto& a,const auto& b){return a.first<b.first;};
  std::sort(locals.begin(),locals.end(),order); std::sort(fixed.begin(),fixed.end(),order);
  for(auto& entry:locals) fn["locals"].push_back(std::move(entry.second));
  for(auto& entry:fixed) fn["implicit_parameters"].push_back(std::move(entry.second));
}
static uint32_t float_bits(float value) {
  uint32_t bits; std::memcpy(&bits,&value,4); return bits;
}
static json static_atom(const StaticResult& value,const StaticNames& names) {
  if(value.is_reference()) return {{"kind","data"},{"target",names.at(value.reference())}};
  if(value.is_symbol()) return {{"kind","pointer"},{"target",value.symbol_name()}};
  if(value.is_func()) return {{"kind","function"},{"target",value.function()->name()}};
  if(value.is_constant_data() && value.constant().size()==8 && integer_fits(value.constant_u64(),4,true))
    return {{"kind","constant"},{"value_bits",static_cast<uint32_t>(value.constant_s32())}};
  return {{"kind","unsupported"}};
}
static json instruction(IR* ir,const StaticNames& statics,const TypeSystem& types) {
  const auto rai=ir->to_rai();
  json output={{"kind","unsupported"},{"text",ir->print()},
               {"reads",json::array()},{"writes",json::array()},{"jumps",rai.jumps}};
  for(const auto& r:rai.read) output["reads"].push_back(r.id);
  for(const auto& r:rai.write) output["writes"].push_back(r.id);
  if(auto* constant=dynamic_cast<IR_LoadConstant64*>(ir)) {
    output["kind"]="constant"; output["value"]=constant->value();
  } else if(auto* load=dynamic_cast<IR_StaticVarLoad*>(ir)) {
    if(auto* value=dynamic_cast<const StaticFloat*>(load->object())) {
      output["kind"]="float_constant"; output["value_bits"]=float_bits(value->value);
    }
  } else if(auto* address=dynamic_cast<IR_StaticVarAddr*>(ir)) {
    output["kind"]="static_address"; output["static_id"]=statics.at(address->object());
  } else if(auto* symbol=dynamic_cast<IR_LoadSymbolPointer*>(ir)) {
    output["kind"]="symbol_pointer"; output["symbol"]=symbol->symbol();
  } else if(auto* symbol_value=dynamic_cast<IR_GetSymbolValue*>(ir)) {
    output["kind"]="symbol_value"; output["symbol"]=symbol_value->symbol();
    output["signed"]=symbol_value->signed_value();
  } else if(auto* set_symbol=dynamic_cast<IR_SetSymbolValue*>(ir)) {
    output["kind"]="set_symbol"; output["symbol"]=set_symbol->symbol();
  } else if(auto* function=dynamic_cast<IR_FunctionAddr*>(ir)) {
    output["kind"]="function_address"; output["function"]=function->function()->name();
  } else if(auto* load=dynamic_cast<IR_LoadConstOffset*>(ir)) {
    output["kind"]="load_memory"; output["offset"]=load->offset();
    output["size"]=load->load_info().size; output["signed"]=load->load_info().sign_extend;
    output["memory_class"]=reg_class(load->load_info().reg);
  } else if(auto* store=dynamic_cast<IR_StoreConstOffset*>(ir)) {
    output["kind"]="store_memory"; output["offset"]=store->offset(); output["size"]=store->size();
  } else if(auto* call=dynamic_cast<IR_FunctionCall*>(ir)) {
    if(rai.write.size()!=2) throw std::runtime_error("unexpected call write layout");
    output["kind"]="call";
    // The desktop emitter temporarily rebases/clobbers the function register.
    // Native SH-4 uses its absolute address directly; only the result is written.
    output["writes"]=call->result()->type().print()=="none" ? json::array() : json::array({rai.write[1].id});
    output["abi"]={{"parameters",json::array()},{"return_type",call->result()->type().print()}};
    for(const auto* argument:call->arguments()) output["abi"]["parameters"].push_back(argument->type().print());
    output["function_type"]=call->function()->type().print();
    output["abi"]["return_abi_type"]=native_value_type(call->result()->type(),types);
    output["abi"]["parameter_abi_types"]=json::array();
    for(const auto* argument:call->arguments())
      output["abi"]["parameter_abi_types"].push_back(native_value_type(argument->type(),types));
  } else if(dynamic_cast<IR_RegSet*>(ir)) {
    output["kind"]="move";
  } else if(dynamic_cast<IR_FloatToInt*>(ir)) {
    output["kind"]="float_to_int";
  } else if(dynamic_cast<IR_IntToFloat*>(ir)) {
    output["kind"]="int_to_float";
  } else if(auto* integer=dynamic_cast<IR_IntegerMath*>(ir)) {
    static const char* names[]={"add64","sub64","imul32","imul64","idiv32","udiv32",
      "shlv64","sarv64","shrv64","shl64","sar64","shr64","imod32","umod32",
      "or64","and64","xor64","not64"};
    const auto index=static_cast<unsigned>(integer->get_kind());
    if(index>=sizeof(names)/sizeof(names[0])) throw std::runtime_error("unknown integer IR");
    output["kind"]=names[index];
    if (integer->get_kind()==IntegerMathKind::SHL_64 || integer->get_kind()==IntegerMathKind::SAR_64 ||
        integer->get_kind()==IntegerMathKind::SHR_64) output["shift"]=integer->shift_amount();
  } else if(auto* floating=dynamic_cast<IR_FloatMath*>(ir)) {
    static const char* names[]={"div_float","mul_float","add_float","sub_float","min_float","max_float","sqrt_float"};
    const auto index=static_cast<unsigned>(floating->get_kind());
    if(index>=sizeof(names)/sizeof(names[0])) throw std::runtime_error("unknown float IR");
    output["kind"]=names[index];
  } else if(auto* branch=dynamic_cast<IR_ConditionalBranch*>(ir)) {
    static const char* names[]={"ne","eq","le","lt","gt","ge","invalid"};
    output["kind"]="branch";
    output["condition"]=names[static_cast<unsigned>(branch->condition.kind)];
    output["signed"]=branch->condition.is_signed;
    output["float"]=branch->condition.is_float;
    output["target"]=branch->label.idx;
  } else if(dynamic_cast<IR_GotoLabel*>(ir)) {
    output["kind"]="goto";
    if(rai.jumps.size()!=1) throw std::runtime_error("unresolved goto");
    output["target"]=rai.jumps[0];
  } else if(dynamic_cast<IR_Return*>(ir)) {
    output["kind"]="return";
  } else if(dynamic_cast<IR_Null*>(ir)||dynamic_cast<IR_Nop*>(ir)||dynamic_cast<IR_ValueReset*>(ir)) {
    output["kind"]="nop";
  }
  return output;
}

int main(int argc,char** argv) {
  if(argc<4) {
    std::cerr<<"Usage: goalc-dreamcast-ir PROJECT_ROOT SOURCE.gc OUTPUT.json [--preload CONTEXT.gc] [--prefix-through-global NAME | TOP_LEVEL_DEFUN ...]\n";
    return 2;
  }
  try {
    lg::initialize();
    if(!file_util::setup_project_path(fs::path(argv[1])))
      throw std::runtime_error("project setup failed");
    Compiler compiler(GameVersion::Jak1,emitter::InstructionSet::X86);
    std::vector<std::string> preloads,selected_names;
    std::string prefix_global;
    std::unordered_set<std::string> context_paths;
    const auto main_path=std::filesystem::weakly_canonical(argv[2]).string();
    for(int i=4;i<argc;++i) {
      if(std::string(argv[i])=="--preload") {
        if(++i>=argc) throw std::runtime_error("--preload requires a source path");
        const auto path=std::filesystem::weakly_canonical(argv[i]);
        if(!std::filesystem::is_regular_file(path) || !context_paths.insert(path.string()).second)
          throw std::runtime_error("missing, duplicate or self-referential preload source");
        preloads.push_back(path.string());
      } else if(std::string(argv[i])=="--prefix-through-global") {
        if(++i>=argc || !prefix_global.empty())
          throw std::runtime_error("--prefix-through-global requires one unique global name");
        prefix_global=argv[i];
        if(prefix_global.empty()) throw std::runtime_error("empty prefix boundary global");
      } else selected_names.push_back(argv[i]);
    }
    if(!prefix_global.empty() && !selected_names.empty())
      throw std::runtime_error("prefix selection and selected defuns are mutually exclusive");
    const bool selected_source_preloaded=context_paths.count(main_path)!=0;
    if(selected_source_preloaded && selected_names.empty())
      throw std::runtime_error("self-referential preload requires selected top-level defuns");
    for(size_t i=0;i<preloads.size();++i) {
      const auto context=compiler.get_goos().reader.read_from_file({preloads[i]});
      compiler.compile_object_file("dreamcast-context-"+std::to_string(i),context,true);
    }
    auto source=compiler.get_goos().reader.read_from_file({std::filesystem::absolute(argv[2]).string()});
    // Select original reader objects without copying or rewriting game bodies.
    // This is for isolated leaf-function tests; dependencies must be explicit.
    if(!selected_names.empty()) {
      std::unordered_set<std::string> missing;
      for(const auto& name:selected_names)
        if(!missing.insert(name).second) throw std::runtime_error("duplicate selected defun");
      std::vector<goos::Object> selected;
      auto forms=source.as_pair()->cdr;
      while(forms.is_pair()) {
        const auto form=forms.as_pair()->car;
        if(form.is_pair() && form.as_pair()->car.is_symbol("defun")) {
          const auto tail=form.as_pair()->cdr;
          if(tail.is_pair() && tail.as_pair()->car.is_symbol() &&
             missing.erase(tail.as_pair()->car.as_symbol().name_ptr)) selected.push_back(form);
        }
        forms=forms.as_pair()->cdr;
      }
      if(!missing.empty()) throw std::runtime_error("selected top-level defun not found: "+*missing.begin());
      auto body=goos::Object::make_empty_list();
      for(auto it=selected.rbegin();it!=selected.rend();++it) body=goos::PairObject::make_new(*it,body);
      source=goos::PairObject::make_new(goos::Object::make_symbol(&compiler.get_goos().reader.symbolTable,"top-level"),body);
    }
    json source_selection={{"kind",selected_names.empty()?"full_source":"selected_defuns"}};
    if(!prefix_global.empty()) {
      std::vector<goos::Object> prefix;
      bool boundary_found=false;
      auto forms=source.as_pair()->cdr;
      while(forms.is_pair()) {
        const auto form=forms.as_pair()->car;
        bool is_boundary=false;
        if(form.is_pair() && form.as_pair()->car.is_symbol("define")) {
          const auto tail=form.as_pair()->cdr;
          is_boundary=tail.is_pair() && tail.as_pair()->car.is_symbol(prefix_global);
        }
        if(is_boundary && boundary_found) throw std::runtime_error("ambiguous prefix boundary global");
        if(!boundary_found) prefix.push_back(form);
        if(is_boundary) boundary_found=true;
        forms=forms.as_pair()->cdr;
      }
      if(!boundary_found) throw std::runtime_error("prefix boundary global not found: "+prefix_global);
      auto body=goos::Object::make_empty_list();
      for(auto it=prefix.rbegin();it!=prefix.rend();++it) body=goos::PairObject::make_new(*it,body);
      source=goos::PairObject::make_new(goos::Object::make_symbol(&compiler.get_goos().reader.symbolTable,"top-level"),body);
      source_selection={{"kind","prefix_through_global"},{"global",prefix_global},{"top_level_forms",prefix.size()}};
    }
    auto* file=compiler.compile_object_file("dreamcast-export",source,true);
    json output={{"format_version",1},{"frontend","OpenGOAL original typed frontend"},
                 {"scope","SH-4 lowering input; unsupported IR remains explicit"},
                 {"preloads",preloads},{"selected_source_preloaded",selected_source_preloaded},{"source_selection",source_selection},
                 {"source",std::filesystem::absolute(argv[2]).string()},{"functions",json::array()}};
    StaticNames statics;
    output["statics"]=json::array();
    for(const auto& object:file->statics()) {
      const auto id="static_"+std::to_string(statics.size());
      statics.emplace(object.get(),id);
    }
    for(const auto& object:file->statics()) {
      const auto& id=statics.at(object.get());
      json entry={{"id",id},{"kind","unsupported"},{"description",object->print()}};
      if(auto* string=dynamic_cast<const StaticString*>(object.get())) {
        entry["kind"]="string";
        entry["text_bytes"]=std::vector<uint8_t>(string->text.begin(),string->text.end());
      } else if(auto* floating=dynamic_cast<const StaticFloat*>(object.get())) {
        entry["kind"]="float"; entry["value_bits"]=float_bits(floating->value);
      } else if(auto* pair=dynamic_cast<const StaticPair*>(object.get())) {
        entry["kind"]="pair";
        entry["car"]=static_atom(pair->car(),statics); entry["cdr"]=static_atom(pair->cdr(),statics);
      }
      output["statics"].push_back(std::move(entry));
    }
    for(const auto& function:file->functions()) {
      json fn={{"name",function->name()},{"asm",function->is_asm_func},
               {"return_type","none"},{"return_abi_type","none"},
               {"top_level",function.get()==&file->top_level_function()},
               {"registers",json::array()},{"parameters",json::array()},{"instructions",json::array()}};
      export_parameters(*function,compiler.type_system(),fn);
      BlockEnv* shared_block=nullptr;
      for(const auto& environment:function->child_envs()) {
        auto* block=dynamic_cast<BlockEnv*>(environment.get());
        if(block && block->parent()==function.get() && block->name=="#f") {
          if(shared_block) throw std::runtime_error("ambiguous function return block");
          shared_block=block;
        }
      }
      bool shared_exit=false,normal_return=false;
      TypeSpec result_type("none");
      for(const auto& op:function->code()) {
        if(auto* ret=dynamic_cast<IR_Return*>(op.get())) {
          if(ret->value()) { normal_return=true; result_type=ret->value()->type(); }
        }
        if(shared_block && shared_block->return_value && dynamic_cast<IR_RegSet*>(op.get())) {
          const auto rai=op->to_rai();
          if(rai.write.size()==1 && rai.write[0].id==shared_block->return_value->ireg().id)
            shared_exit=true;
        }
      }
      shared_exit=shared_exit && !function->is_asm_func;
      if(shared_exit) {
        if(shared_block->end_label.idx<0 ||
           static_cast<size_t>(shared_block->end_label.idx)+1!=function->code().size() ||
           !dynamic_cast<IR_Null*>(function->code().back().get()))
          throw std::runtime_error("unsupported shared function exit layout");
        if(normal_return) result_type=compiler.type_system().lowest_common_ancestor(shared_block->return_types);
        else for(const auto& type:shared_block->return_types)
          if(type!=TypeSpec("none")) throw std::runtime_error("value early return without a declared normal return is unsupported");
        fn["shared_exit"]={{"register",shared_block->return_value->ireg().id},
                           {"exit_ir",shared_block->end_label.idx}};
      }
      fn["return_type"]=result_type.print();
      fn["return_abi_type"]=native_value_type(result_type,compiler.type_system());
      std::unordered_map<int,json> fixed_registers;
      fn["fixed_registers"]=json::array();
      for(const auto& constraint:function->constraints()) {
        if(!constraint.contrain_everywhere) continue;
        const auto name=constraint.desired_register.print(emitter::InstructionSet::X86);
        json binding={{"register",constraint.ireg.id},{"frontend_register",name},
                      {"role",name=="r14" ? "symbol_table" : "unsupported"}};
        const auto found=fixed_registers.find(constraint.ireg.id);
        if(found!=fixed_registers.end()) {
          if(found->second!=binding) throw std::runtime_error("conflicting fixed register constraints");
        } else {
          fixed_registers.emplace(constraint.ireg.id,binding);
          fn["fixed_registers"].push_back(binding);
        }
      }
      std::unordered_set<int> no_values;
      std::unordered_map<int,json> register_records;
      std::unordered_map<int,size_t> alias_counts;
      for(const auto& value:function->reg_vals()) {
        const auto type=shared_exit && value.get()==shared_block->return_value ? result_type : value->type();
        const int id=value->ireg().id;
        json record={{"id",id},{"class",reg_class(value->ireg().reg_class)},
                     {"type",type.print()},{"abi_type",native_value_type(type,compiler.type_system())}};
        const auto found=register_records.find(id);
        if(found!=register_records.end()) {
          if(!fixed_registers.count(id) || found->second!=record)
            throw std::runtime_error("conflicting or non-fixed virtual register alias in "+function->name());
        } else {
          register_records.emplace(id,record); fn["registers"].push_back(record);
        }
        ++alias_counts[id];
        if(type.print()=="none") no_values.insert(value->ireg().id);
      }
      fn["register_aliases"]=json::array();
      for(const auto& record:fn["registers"]) {
        const int id=record.at("id").get<int>();
        if(alias_counts.at(id)>1) fn["register_aliases"].push_back({{"register",id},{"count",alias_counts.at(id)}});
      }
      size_t position=0;
      for(const auto& op:function->code()) {
        auto exported=instruction(op.get(),statics,compiler.type_system());
        const auto rai=op->to_rai();
        if(dynamic_cast<IR_ValueReset*>(op.get()) && !rai.write.empty()) {
          bool all_fixed=true;
          for(const auto& reg:rai.write) if(!fixed_registers.count(reg.id)) all_fixed=false;
          if(all_fixed) {
            exported["kind"]="fixed_register_reset"; exported["bindings"]=json::array();
            for(const auto& reg:rai.write) exported["bindings"].push_back(fixed_registers.at(reg.id));
          }
        }
        // The original frontend copies its phantom call-result register even
        // for (none). No native value exists; retain its IR index as a no-op.
        if(dynamic_cast<IR_RegSet*>(op.get()) && rai.read.size()==1 && rai.write.size()==1 &&
           no_values.count(rai.read[0].id) && no_values.count(rai.write[0].id)) {
          exported["kind"]="nop"; exported["reads"]=json::array(); exported["writes"]=json::array();
        }
        // Desktop IR_Return assigns the shared result; it is not a machine
        // return. Preserve every original index and make the outer null label
        // the actual exit so early and normal paths share liveness/validation.
        if(shared_exit && dynamic_cast<IR_Return*>(op.get())) exported["kind"]="move";
        if(shared_exit && position==static_cast<size_t>(shared_block->end_label.idx)) {
          exported["kind"]="return";
          exported["reads"]=result_type==TypeSpec("none") ? json::array() :
              json::array({shared_block->return_value->ireg().id});
          exported["writes"]=json::array();
          exported["text"]="shared function exit";
        }
        fn["instructions"].push_back(std::move(exported));
        ++position;
      }
      output["functions"].push_back(std::move(fn));
    }
    std::ofstream stream(std::filesystem::path(argv[3]),std::ios::binary);
    if(!stream) throw std::runtime_error("cannot open IR output");
    stream<<output.dump(2)<<'\n';
    if(!stream) throw std::runtime_error("IR write failed");
    return 0;
  } catch(const std::exception& error) {
    std::cerr<<"Dreamcast frontend export failed: "<<error.what()<<'\n';
    return 1;
  }
}
