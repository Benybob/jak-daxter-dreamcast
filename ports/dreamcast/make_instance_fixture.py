"""Stage a DCI1 package for the instance-pass diagnostic (AI-assisted), ISC.

    python make_instance_fixture.py ASSET_DIR --header build/instance_fixture.h

ASSET_DIR/package.dci is the package to draw: a real level's, written there by
`prototype_geometry.py DGO GLB --out ASSET_DIR/package.dci` and never committed,
or, when it is missing, a small synthetic one written here. The header carries
the package's size and CRC, a camera aimed at the package's densest 16 m cell
(by LOD 0 triangles), and the instance and triangle counts dc_instance_draw
must visit with it, worked out here in single precision as the C does.
"""
import argparse
import json
import math
import struct
from pathlib import Path
import zlib

import prototype_geometry

CELL_M = 16.0
YAW, PITCH, DISTANCE, DRAW_DISTANCE = 2.2, -0.45, 55.0, 80.0


def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def synthetic():
    """A unit-ish block prototype placed on a 5x5 grid, three colours."""
    corners = [(x, y, z) for x in (0.0, 1.0) for y in (0.0, 2.0) for z in (0.0, 1.0)]
    faces = [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)]
    geometry = []
    for n, (a, b, c, d) in enumerate(faces):
        col = [(220, 80, 40, 255), (60, 180, 90, 255), (70, 110, 230, 255)][n % 3]
        for tri in ((a, b, c), (a, c, d)):
            geometry.append(([corners[i] for i in tri], [(0.0, 0.0)] * 3, [col] * 3, 0))
    origin = [4096, 0, 0, 0, 0, 4096, 0, 0, 0, 0, 4096, 0, 0, 0, 0, 0]
    instances = [{'proto': 0, 'origin': origin, 'x': 3.0 * i, 'y': 0.0, 'z': 3.0 * k}
                 for i in range(-2, 3) for k in range(-2, 3)]
    blob, _ = prototype_geometry.package([{'name': 'block', 'geometry': geometry}], instances)
    return blob


def read(blob):
    """(prototype records, instances) of a DCI1 package; for DCI2 the records are
    the geometries and each instance points at its prototype's LOD 0 geometry."""
    if blob[:4] == b'DCI2':
        import tie_lods
        geoms, table, _, _, instances = tie_lods.read_dci2(blob)
        return [g[:5] for g in geoms], [(table[p][0], pad, *m) for p, pad, *m in instances]
    _, n_protos, n_inst = struct.unpack_from('<4s2I', blob, 0)
    protos = [struct.unpack_from('<5I', blob, 12 + 52 * i) for i in range(n_protos)]
    at = 12 + 52 * n_protos + 24 * sum(p[0] for p in protos) + 2 * sum(p[1] for p in protos)
    at = (at + 3) & ~3
    instances = [struct.unpack_from('<2H12f', blob, at + 52 * i) for i in range(n_inst)]
    return protos, instances


def camera(protos, instances):
    cells = {}
    for proto, _, *m in instances:
        key = (math.floor(m[9] / CELL_M), math.floor(m[11] / CELL_M))
        tris, xs = cells.get(key, (0, []))
        cells[key] = (tris + protos[proto][1] // 3, xs + [m[9:12]])
    key, (_, points) = max(cells.items(), key=lambda kv: (kv[1][0], kv[0]))
    target = [sum(p[i] for p in points) / len(points) for i in range(3)]
    target[1] = sorted(p[1] for p in points)[len(points) // 2] + 2.0
    return [f32(v) for v in target]


def expected(protos, instances, target, draw_distance):
    tx, tz, dd = f32(target[0]), f32(target[2]), f32(draw_distance)
    drawn = tris = 0
    for proto, _, *m in instances:
        dx, dz = f32(f32(m[9]) - tx), f32(f32(m[11]) - tz)
        if f32(f32(dx * dx) + f32(dz * dz)) > f32(dd * dd):
            continue
        drawn += 1
        tris += protos[proto][1] // 3
    return drawn, tris


def lod_counts(blob, target, draw_distance):
    """Instances drawn at each LOD 0..3 (all at 0 for DCI1)."""
    counts = [0, 0, 0, 0]
    tx, tz, dd = f32(target[0]), f32(target[2]), f32(draw_distance)
    if blob[:4] != b'DCI2':
        counts[0] = expected(*read(blob), target, draw_distance)[0]
        return counts
    import tie_lods
    _, table, _, _, instances = tie_lods.read_dci2(blob)
    for proto, _, *m in instances:
        dx, dz = f32(f32(m[9]) - tx), f32(f32(m[11]) - tz)
        d2 = f32(f32(dx * dx) + f32(dz * dz))
        if d2 > f32(dd * dd):
            continue
        row, plane = table[proto][:4], table[proto][4:7]
        lod = sum(1 for p in plane if d2 > f32(f32(p) * f32(p)))
        while row[lod] == tie_lods.NONE:
            lod -= 1
        counts[lod] += 1
    return counts


def make(asset_dir, header, draw_distance=DRAW_DISTANCE):
    asset_dir.mkdir(parents=True, exist_ok=True)
    path = asset_dir / 'package.dci'
    if not path.is_file():
        path.write_bytes(synthetic())
    blob = path.read_bytes()
    real = blob != synthetic()
    protos, instances = read(blob)
    target = camera(protos, instances)
    view = blob
    if blob[:4] == b'DCI2':
        import tie_lods
        view = tie_lods.flatten(blob, target[0], target[2])
    drawn, tris = expected(*read(view), target, draw_distance)
    lods = lod_counts(blob, target, draw_distance)
    text = ('/* Generated by make_instance_fixture.py (AI-assisted); not committed. */\n'
            f'#define INSTANCE_PACKAGE_BYTES {len(blob)}u\n#define INSTANCE_PACKAGE_CRC {zlib.crc32(blob)}u\n'
            f'#define INSTANCE_PROTOTYPES {len(protos)}u\n#define INSTANCE_COUNT {len(instances)}u\n'
            f'#define INSTANCE_EXPECTED_DRAWN {drawn}u\n#define INSTANCE_EXPECTED_TRIANGLES {tris}u\n'
            f'#define INSTANCE_SYNTHETIC {int(not real)}\n#define INSTANCE_LODS {int(blob[:4] == b"DCI2")}\n'
            f'static const uint32_t instance_expected_lods[4]={{{lods[0]}u,{lods[1]}u,{lods[2]}u,{lods[3]}u}};\n'
            'static const dc_instance_camera instance_camera={%s};\n'
            % ','.join(repr(f32(v)) + 'f' for v in (*target, YAW, PITCH, DISTANCE, draw_distance)))
    header.parent.mkdir(parents=True, exist_ok=True)
    header.write_text(text, newline='\n')
    report = {'ai_assisted': True, 'original_assets': real, 'package_bytes': len(blob), 'crc': zlib.crc32(blob),
              'prototypes': len(protos), 'instances': len(instances), 'target_m': target,
              'yaw': YAW, 'pitch': PITCH, 'distance_m': DISTANCE, 'draw_distance_m': draw_distance,
              'expected_drawn_instances': drawn, 'expected_triangles': tris, 'expected_lod_instances': lods,
              'format': blob[:4].decode()}
    (asset_dir / 'INSTANCES.json').write_text(json.dumps(report, indent=1), newline='\n')
    return report


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('asset_dir', type=Path)
    ap.add_argument('--header', type=Path, required=True)
    a = ap.parse_args()
    print(json.dumps(make(a.asset_dir, a.header), indent=1))


if __name__ == '__main__':
    main()
