"""Original compiler entry constraints, named locals and fail-closed lowering (AI-assisted)."""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from lower_sh4_ir import compile_function
FRONTEND=Path(os.environ.get('GOAL_IR_FRONTEND',str(ROOT.parents[2]/'og-host/bin/goalc-dreamcast-ir.exe')))

@unittest.skipUnless(FRONTEND.is_file(),'build the original typed frontend for entry/local integration checks')
class FrontendParametersTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.env=os.environ.copy()
        if os.name=='nt': cls.env['PATH']='C:/msys64/mingw64/bin'+os.pathsep+cls.env['PATH']
        cls.directory=tempfile.TemporaryDirectory()
        cls.addClassCleanup(cls.directory.cleanup)
        output=Path(cls.directory.name)/'fixture.ir.json'
        r=subprocess.run([str(FRONTEND),str(ROOT.parents[1]),str(ROOT/'locals_fixture.gc'),str(output)],
                         env=cls.env,capture_output=True,text=True)
        if r.returncode: raise AssertionError(r.stdout+r.stderr)
        cls.doc=json.loads(output.read_text())
        cls.functions={f['name']:f for f in cls.doc['functions']}

    def test_named_locals_do_not_expand_zero_one_or_eight_argument_abi(self):
        for name,count,locals_count in [('zero',0,1),('basic',1,1),('eight',8,2),('mutate',2,2),('float',2,1)]:
            with self.subTest(name=name):
                fn=self.functions['dc-local-'+name]
                self.assertEqual(len(fn['parameters']),count)
                self.assertEqual(len(fn['locals']),locals_count)
                self.assertEqual(fn['implicit_parameters'],[])
                self.assertTrue(compile_function(fn,runtime=True)[0])

    def test_parameters_keep_declared_order_and_exact_generated_entry_copies(self):
        fn=self.functions['dc-local-eight']
        self.assertEqual([p['name'] for p in fn['parameters']],list('abcdefgh'))
        for op,p in zip(fn['instructions'][1:9],fn['parameters']):
            self.assertEqual((op['reads'],op['writes']),([p['register']],[p['local_register']]))
        self.assertFalse({p['local_register'] for p in fn['parameters']} & {p['register'] for p in fn['locals']})

    def test_mutated_parameters_and_a_local_named_self_remain_distinct(self):
        fn=self.functions['dc-local-mutate']
        self.assertEqual([p['name'] for p in fn['parameters']],['left','right'])
        self.assertEqual({p['name'] for p in fn['locals']},{'copy','self'})
        self.assertEqual(fn['implicit_parameters'],[])

    def test_methods_use_the_same_constrained_entry_mapping(self):
        candidates=[f for f in self.doc['functions'] if 'dc-local-record' in f['name'] and f['parameters']]
        self.assertEqual(len(candidates),1)
        fn=candidates[0]
        self.assertEqual([p['name'] for p in fn['parameters']],['this'])
        self.assertEqual([p['name'] for p in fn['locals']],['scratch'])
        self.assertTrue(compile_function(fn,runtime=True)[0])

    def test_uninitialized_and_partially_initialized_locals_still_fail(self):
        for name in ('uninitialized','partial'):
            with self.subTest(name=name),self.assertRaisesRegex(ValueError,'uninitialized virtual'):
                compile_function(self.functions['dc-local-'+name],runtime=True)
        self.assertTrue(compile_function(self.functions['dc-local-branch'],runtime=True)[0])

    def test_fixed_entry_metadata_is_never_assumed_to_be_a_positional_argument(self):
        fn=dict(self.functions['dc-local-basic'],implicit_parameters=[{'name':'self','register':99,'kind':'fixed_entry'}])
        for runtime in (False,True):
            with self.subTest(runtime=runtime),self.assertRaisesRegex(ValueError,'implicit process/self'):
                compile_function(fn,runtime=runtime)

    def test_original_behavior_process_entry_is_exported_separately_and_rejected(self):
        functions=[f for f in self.doc['functions'] if f.get('implicit_parameters')]
        self.assertEqual(len(functions),1)
        fn=functions[0]
        self.assertEqual([p['name'] for p in fn['parameters']],['arg'])
        self.assertEqual([p['name'] for p in fn['implicit_parameters']],['self'])
        self.assertEqual(fn['locals'],[])
        self.assertNotIn(fn['implicit_parameters'][0]['register'],[p['register'] for p in fn['parameters']])
        with self.assertRaisesRegex(ValueError,'implicit process/self'):
            compile_function(fn,runtime=True)

    def test_autogenerated_inspect_argument_comes_from_its_constrained_regval(self):
        fn=self.functions['autogenerated-inspect-method-of-dc-local-auto']
        self.assertEqual(len(fn['parameters']),1)
        p=fn['parameters'][0]
        self.assertEqual((p['name'],p['name_source'],p['type']),('arg-0','frontend-generated','dc-local-auto'))
        self.assertEqual((fn['instructions'][1]['reads'],fn['instructions'][1]['writes']),
                         ([p['register']],[p['local_register']]))
        self.assertEqual((fn['locals'],fn['implicit_parameters']),([],[]))
