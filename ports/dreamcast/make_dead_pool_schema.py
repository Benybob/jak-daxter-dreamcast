"""Read original type-constructor constants from frontend IR (AI-assisted), ISC.

This exports metadata only. It does not lower/execute the whole kernel header
or omit its unsupported autogenerated inspection methods from a claimed boot.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess

PORT=Path(__file__).resolve().parent


def extract(doc):
    initializers=[f for f in doc['functions'] if f['name']=='top-level']
    if len(initializers)!=1:raise ValueError('one original header initializer is required')
    values={};found=[]
    for op in initializers[0]['instructions']:
        kind=op['kind'];reads=op['reads'];writes=op['writes'];value=None
        if kind in ('branch','goto'):raise ValueError('type metadata must be straight-line')
        if kind in ('symbol_pointer','symbol_value'):value=(kind,op['symbol'])
        elif kind=='constant':value=('constant',int(op['value']))
        elif kind=='move' and len(reads)==1:value=values.get(reads[0])
        elif kind=='load_memory' and op.get('offset')==16 and op.get('size')==4 and len(reads)==1:
            if values.get(reads[0])==('symbol_value','type'):value=('type_constructor',)
        elif kind=='call' and reads and values.get(reads[0])==('type_constructor',):
            args=[values.get(i) for i in reads[1:]]
            if args and args[0]==('symbol_pointer','dead-pool'):
                if len(args)!=3 or args[1]!=('symbol_value','process-tree') or not args[2] or args[2][0]!='constant':
                    raise ValueError('original dead-pool constructor metadata is incomplete')
                found.append(args[2][1])
        for index in writes:values[index]=value
    if len(found)!=1:raise ValueError('one original dead-pool type constructor is required')
    flags=found[0]
    if flags<0 or flags>>48:raise ValueError('unsupported original type flags')
    return dict(parent='process-tree',flags=flags,size=flags&65535,
                heap_base=(flags>>16)&65535,methods=(flags>>32)&65535)


def generate(frontend,header,runtime_bin=None):
    repo=PORT.parents[1];source=repo/'goal_src/jak1/kernel/gkernel-h.gc'
    preloads=[repo/'goal_src/jak1/kernel/gcommon.gc',PORT/'scalar_validation_context.gc']
    header=Path(header);header.parent.mkdir(parents=True,exist_ok=True);ir=header.with_suffix('.ir.json')
    command=[str(Path(frontend).resolve()),str(repo),str(source),str(ir.resolve())]
    for p in preloads:command+=['--preload',str(p)]
    env=os.environ.copy()
    if runtime_bin is None and os.name=='nt' and Path('C:/msys64/mingw64/bin').is_dir():
        runtime_bin=Path('C:/msys64/mingw64/bin')
    if runtime_bin:env['PATH']=str(Path(runtime_bin).resolve())+os.pathsep+env['PATH']
    subprocess.run(command,check=True,capture_output=True,text=True,env=env)
    doc=json.loads(ir.read_text());schema=extract(doc)
    report=dict(ai_assisted=True,scope='Original frontend type metadata only; whole header startup remains unsupported',
                source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                frontend_sha256=hashlib.sha256(Path(frontend).read_bytes()).hexdigest(),
                ir_sha256=hashlib.sha256(ir.read_bytes()).hexdigest(),schema=schema)
    header.write_text('/* Original dead-pool metadata, not a whole-header initializer (AI-assisted), ISC. */\n'
        '#include <stdint.h>\n'+f'#define DC_ORIGINAL_DEAD_POOL_FLAGS UINT64_C({schema["flags"]})\n'+
        f'#define DC_ORIGINAL_DEAD_POOL_SIZE {schema["size"]}u\n#define DC_ORIGINAL_DEAD_POOL_METHODS {schema["methods"]}u\n'+
        '/* gkernel-h.gc SHA256 '+report['source_sha256']+' */\n')
    header.with_suffix('.manifest.json').write_text(json.dumps(report,indent=2)+'\n')
    return report


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--frontend',type=Path,required=True)
    p.add_argument('--header',type=Path,default=PORT/'build/original_dead_pool_schema.h')
    p.add_argument('--runtime-bin',type=Path,help='Optional Windows compiler runtime DLL directory');a=p.parse_args()
    print(json.dumps(generate(a.frontend,a.header,a.runtime_bin),indent=2))
